import { describe, it, expect } from "vitest";
import {
  bytes,
  dependency,
  objectSchema,
  replaceCollection,
  types,
  variants,
} from "./model";
const schema = {
  properties: {
    inbounds: { type: "array", items: { $ref: "#/$defs/Inbound" } },
    route: { $ref: "#/$defs/Route" },
  },
  $defs: {
    Inbound: {
      oneOf: [
        {
          properties: {
            type: { const: "shadowsocks" },
            method: { enum: ["aes-128-gcm"] },
          },
        },
        { properties: { type: { const: "vless" }, users: { type: "array" } } },
      ],
    },
    Route: { properties: { rules: { items: { $ref: "#/$defs/Rule" } } } },
    Rule: {
      oneOf: [
        {
          allOf: [
            { properties: { domain: { type: "array" } } },
            { $ref: "#/$defs/Action" },
          ],
        },
        {
          allOf: [
            {
              properties: {
                type: { const: "logical" },
                mode: { enum: ["and", "or"] },
              },
            },
            { $ref: "#/$defs/Action" },
          ],
        },
      ],
    },
    Action: {
      oneOf: [
        {
          properties: {
            action: { const: "route" },
            outbound: { type: "string" },
          },
        },
        { properties: { action: { const: "reject" } } },
      ],
    },
  },
};
describe("installed schema discovery", () => {
  it("uses only binary protocol discriminants", () => {
    expect(types(schema, "inbounds")).toEqual(["shadowsocks", "vless"]);
    expect(
      objectSchema(schema, "inbounds", "vless").properties.method,
    ).toBeUndefined();
  });
  it("preserves matching fields across action unions", () => {
    expect(objectSchema(schema, "rules", "").properties.domain).toEqual({
      type: "array",
    });
    expect(
      objectSchema(schema, "rules", "logical").properties.mode.enum,
    ).toEqual(["and", "or"]);
    expect(variants(schema, schema.$defs.Action)).toHaveLength(2);
  });
});
describe("lossless config operations", () => {
  it("retains unrelated configuration and unknown fields", () => {
    const old = {
      dns: { future: { x: 1 } },
      route: { unknown: true, rules: [{ domain: ["old"] }] },
      privateKey: "unchanged",
    };
    const next = replaceCollection(old, "rules", [{ domain: ["new"] }]);
    expect(next.dns).toEqual(old.dns);
    expect(next.route.unknown).toBe(true);
    expect(old.route.rules[0].domain).toEqual(["old"]);
  });
  it("finds nested dependencies", () => {
    expect(
      dependency(
        {
          route: {
            rules: [{ type: "logical", rules: [{ outbound: "proxy" }] }],
          },
        },
        "proxy",
      ),
    ).toBe(true);
    expect(dependency({ outbounds: [{ tag: "proxy" }] }, "proxy")).toBe(false);
  });
  it("does not fabricate unavailable totals", () => {
    expect(bytes(undefined)).toBe("—");
    expect(bytes(0)).toBe("0 B");
    expect(bytes(1024)).toBe("1.0 KB");
  });
});

// Test-only fixture generated by the verified official 1.14.4 darwin-arm64 binary.
// Production always fetches the currently installed binary's /api/schema.
import installedSchema from "./fixtures/sing-box-1.14.4.schema.json";
import { matchSchema, resolve, sectionSchema, tagNames } from "./model";
describe("official sing-box 1.14.4 generated schema regression", () => {
  it("discovers installed protocols and protocol-specific credential controls", () => {
    expect(types(installedSchema, "inbounds")).toContain("anytls");
    const ss = objectSchema(installedSchema, "inbounds", "shadowsocks");
    expect(ss.properties.method.enum).toContain("2022-blake3-aes-128-gcm");
    const vless = objectSchema(installedSchema, "inbounds", "vless");
    expect(vless.properties.method).toBeUndefined();
    expect(
      resolve(installedSchema, vless.properties.users).items,
    ).toBeDefined();
    expect(
      resolve(installedSchema, vless.properties.tls).properties.enabled.type,
    ).toBe("boolean");
  });
  it("keeps native match conditions separate from THEN actions", () => {
    const when = matchSchema(installedSchema, "");
    expect(when.properties.domain_suffix).toBeDefined();
    expect(when.properties.rule_set).toBeDefined();
    expect(when.properties.action).toBeUndefined();
    expect(when.properties.outbound).toBeUndefined();
    const group = matchSchema(installedSchema, "logical");
    expect(group.properties.mode.enum).toEqual(["and", "or"]);
    expect(group.properties.rules.items).toBeDefined();
  });
  it("discovers inline local remote rule sets and preserves tag requirements", () => {
    expect(types(installedSchema, "rule_set")).toEqual(
      expect.arrayContaining(["inline", "local", "remote"]),
    );
    for (const type of ["inline", "local", "remote"])
      expect(
        objectSchema(installedSchema, "rule_set", type).properties.tag,
      ).toBeDefined();
    expect(
      variants(installedSchema, sectionSchema(installedSchema, "rule_set"))
        .length,
    ).toBeGreaterThanOrEqual(3);
  });
  it("keeps selector references constrained to native schema fields", () => {
    const selector = objectSchema(installedSchema, "outbounds", "selector");
    expect(selector.properties.outbounds.items["x-tag-reference"]).toBe(
      "outbound",
    );
  });
});

it("preserves and resolves every name in a rule-set tag list", () => {
  const value = { tag: ["regional", "private"] };
  expect(tagNames(value)).toEqual(["regional", "private"]);
  expect(
    tagNames(value).some((tag) =>
      dependency({ route: { rules: [{ rule_set: "private" }] } }, tag),
    ),
  ).toBe(true);
  expect(tagNames({ tag: "single" })).toEqual(["single"]);
});
